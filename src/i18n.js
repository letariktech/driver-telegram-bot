/** ጽሑፍ ማውጫ — `t(lang, "docs_approved", { stage })` */
export function t(lang, key, vars = {}) {
  const pick = (L) => key.split(".").reduce((o, k) => (o == null ? o : o[k]), L);
  let s = pick(STRINGS[lang] ?? am);
  if (s == null) s = pick(am);
  if (s == null) return key;
  if (typeof s !== "string") return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** የምርጫ ስም — `opt(lang, "fuel", "electric")` */
export function opt(lang, group, value) {
  return STRINGS[lang]?.opt?.[group]?.[value] ?? am.opt[group]?.[value] ?? value;
}

export const pickLang = (code) => {
  const c = String(code ?? "").slice(0, 2).toLowerCase();
  return ["am", "en", "om", "ti"].includes(c) ? c : "am";
};
